def cells():
    nb = json.load(open(NB, encoding='utf-8'))
    c3 = ''.join(nb['cells'][3]['source']); c4 = ''.join(nb['cells'][4]['source'])
    assert hashlib.sha256(c4.encode()).hexdigest() == SRC_SHA256, 'public cell 4 is not the pinned .949 source'
    assert hashlib.sha256(c3.encode()).hexdigest() == CELL3_SHA256, 'public cell 3 is not the pinned weights check'
    assert WEIGHTS_SHA256 in c3 and WEIGHTS_FILE in c3 and WEIGHTS_SHA256 in c4 and WEIGHTS_FILE in c4
    return c3, c4


def make():
    _, src = cells()
    for name, old, new in P:
        k = src.count(old)
        assert k == 1, f'patch {name}: anchor found {k} times (want exactly 1)'
        src = src.replace(old, new)
    src = HEADER + src
    # invariants the K9N cell relies on
    for must in ('K_EVAL = 94', 'INPUT_RES = 320', 'IMG = 384', "FASTREAD_VARIANT = 'study_lut'",
                 'with torch.autocast("cuda", dtype=torch.float16):', 'assert str(device).startswith("cuda")',
                 'xm = gpu_windows(vol, mask, K_EVAL, res, d, norm=NORM, mirror=True)',
                 'nproc = max(4, min(96, (os.cpu_count() or 8) - 8))', 'mp.get_context("fork").Pool'):
        assert src.count(must) == 1, f'child invariant {must!r} count {src.count(must)}'
    assert '/kaggle/working/submission.csv' not in src and "'/kaggle/working/_fastread.py'" not in src
    compile(src, 'n949_child.py', 'exec')
    return src


def main():
    ap = argparse.ArgumentParser(); ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    src = make()
    sha = hashlib.sha256(src.encode()).hexdigest()
    if a.check:
        assert open(OUT, encoding='utf-8', newline='').read() == src, 'n949_child.py != make() (stale)'
        print(f'n949_child.py OK (== make()), sha256 {sha}')
        return
    with open(OUT, 'w', encoding='utf-8', newline='') as fh:
        fh.write(src)
    print(f'wrote {OUT}: {src.count(chr(10))} lines, sha256 {sha}, {len(P)} patches applied once each')


if __name__ == '__main__':
    main()
