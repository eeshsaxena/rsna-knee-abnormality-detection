#!/usr/bin/env python3
"""make_k10_tools.py (2026-10-09, Claude). Generates every K10 file that is a PROVEN kit file + an exact, counted text
substitution (each anchor must match exactly the stated number of times; the reverse substitution must give back the
source byte for byte). Nothing else in the kit is edited by hand. `--check` = every generated file on disk == make().

K10-DS (new dataset slugs, so the live K9 dataset version is never touched):
  cells/k10_fleet_cell.py   = cells/k2_fleet_cell.py (the K5 cell e37f0604997cd40f) with every 'rsna-knee-cnxt-fleet'
                              (3: the two mount paths + the not-attached message) -> 'rsna-knee-cnxt-fleet-k10'
  cells/k10w_fleet_cell.py  = the same -> 'rsna-knee-cnxt-fleet-k10w' (the 15-member C+D+E dataset of FN10-3)
K10-CHK:
  k10n_check.py             = k9n_check.py with the kernel key rsna-sub-k9n-{tag} -> rsna-sub-k10n-{tag}, the N config
                              TAG K9N-{tag} -> K10N-{tag}, the FINAL label and the summary word K9NCHECK -> K10NCHECK
K10-BOX (box A0 harnesses; the fleet dataset symlink name comes from env K10_DS_SLUG, default the K10 slug):
  box/k10_box_stage.py      = box/k2_box_stage.py   (K9 main / solo A0 harness)
  box/k10n_box_stage.py     = box/k9n_box_stage.py  (+ imports k10n_check as k9n_check)
  box/k10fn_box_stage.py    = box/kfn_box_stage.py  (+ imports fn10_check as fn_check)

  python make_k10_tools.py [--check]
"""
import argparse, hashlib, os, sys

HERE = os.path.dirname(os.path.abspath(__file__)).replace('\\', '/')
K5_CELL_SHA16 = 'e37f0604997cd40f'
DS0 = 'rsna-knee-cnxt-fleet'
SLUG_K10, SLUG_K10W = 'rsna-knee-cnxt-fleet-k10', 'rsna-knee-cnxt-fleet-k10w'
SLUG_DEF = ("MIRROR_COMP = f'{HOME}/kmimic/kaggle/input/rsna-knee-abnormality-detection'\n",
            "MIRROR_COMP = f'{HOME}/kmimic/kaggle/input/rsna-knee-abnormality-detection'\n"
            "K10_DS_SLUG = os.environ.get('K10_DS_SLUG', 'rsna-knee-cnxt-fleet-k10')   # K10-DS: the fleet dataset mount "
            "name (negative test: the K9 slug)\n")
LINK = ("f'{inp}/datasets/eeshsaxena/rsna-knee-cnxt-fleet')", "f'{inp}/datasets/eeshsaxena/{K10_DS_SLUG}')")
CR, LF = chr(13), chr(10)
CRLF = CR + LF
SIM_ALLOW = ("{ind}if json.load(open(os.path.expanduser(a.expect_tta))).get('do_not_submit'):   # K10-SIM: a simulation / "
             "interim K5_BUILD.json is never FINAL\n{ind}    argv += ['--allow_interim']   # (its K8-INT line then says TEST "
             "USE ONLY; a FINAL build is gated strictly)\n")
HDR = '# K10: generated by k10/make_k10_tools.py from {src} (exact counted substitutions; never edit by hand)\n'


def sha(s):
    return hashlib.sha256(s.encode() if isinstance(s, str) else s).hexdigest()


def rd(p):
    return open(f'{HERE}/{p}', encoding='utf-8', newline='').read()


def subst(src, pairs):
    out = src
    for old, new, n in pairs:
        c = out.count(old)
        assert c == n, f'anchor {old[:70]!r} found {c} times (want {n})'
        assert new not in out or old in new, f'replacement {new[:60]!r} already present'
        out = out.replace(old, new)
    back = out
    for old, new, n in reversed(pairs):
        back = back.replace(new, old)
    assert back == src, 'reverse substitution does not give back the source'
    return out


def cell(slug):
    src = rd('cells/k2_fleet_cell.py')
    assert sha(src)[:16] == K5_CELL_SHA16, 'cells/k2_fleet_cell.py is not the K5 cell'
    assert src.count(DS0) == 3 and DS0 + '-' not in src
    return subst(src, [(DS0, slug, 3)])


def unpatch_cell(src, slug):
    """The K5 cell back from a K10-DS patched cell (asserted by the builders and tests)."""
    assert src.count(slug) == 3, f'{slug} occurs {src.count(slug)} times'
    return src.replace(slug, DS0)


def k10n_check():
    src = rd('k9n_check.py')
    out = subst(src, [
        ("\"\"\"k9n_check.py (2026-10-08, Claude):",
         "\"\"\"k10n_check.py = k9n_check.py with the K10N kernel key / TAG (k10/make_k10_tools.py, 2026-10-09). k9n_check.py "
         "(2026-10-08, Claude):", 1),
        ("kb['kernels'][f'rsna-sub-k9n-{a.tag}']", "kb['kernels'][f'rsna-sub-k10n-{a.tag}']", 1),
        ("K9N-{a.tag}", "K10N-{a.tag}", 2),
        ("'K9N build is FINAL (K9N_BUILD.json do_not_push false)'", "'K10N build is FINAL (K10N_BUILD.json do_not_push false)'", 1),
        ("print(f'K9NCHECK ", "print(f'K10NCHECK ", 1)])
    return out


def box(src_name, extra):
    src = rd(f'box/{src_name}')
    nl = CRLF if CRLF in src else LF                                   # keep the source line endings (k9n: CRLF)
    assert nl == LF or src.count(CRLF) == src.count(LF), f'{src_name}: mixed line endings'
    fix = lambda t: t.replace(LF, nl)
    pairs = [(fix(o), fix(n), c) for o, n, c in [(SLUG_DEF[0], SLUG_DEF[1], 1), (LINK[0], LINK[1], 1)] + extra]
    return fix(HDR.format(src=f'box/{src_name}')) + subst(src, pairs)


def make():
    return {
        'cells/k10_fleet_cell.py': cell(SLUG_K10),
        'cells/k10w_fleet_cell.py': cell(SLUG_K10W),
        'k10n_check.py': k10n_check(),
        'box/k10_box_stage.py': box('k2_box_stage.py', []),
        'box/k10n_box_stage.py': box('k9n_box_stage.py', [
            ('    import k2_check, k9n_check\n', '    import k2_check, k10n_check as k9n_check   # K10-CHK\n', 1),
            ("n.startswith('K9N build is FINAL')", "n.startswith('K10N build is FINAL')", 1),
            ("        if a.expect_tta:\n            argv += ['--expect_tta', a.expect_tta]\n",
             "        if a.expect_tta:\n            argv += ['--expect_tta', a.expect_tta]\n" + SIM_ALLOW.format(ind=' ' * 12), 1)]),
        'box/k10fn_box_stage.py': box('kfn_box_stage.py', [
            ('    import k2_check, fn_check\n', '    import k2_check, fn10_check as fn_check   # K10-CHK\n', 1),
            ("            if a.expect_tta:\n                argv += ['--expect_tta', a.expect_tta]\n",
             "            if a.expect_tta:\n                argv += ['--expect_tta', a.expect_tta]\n" + SIM_ALLOW.format(ind=' ' * 16), 1)]),
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    files = make()
    bad = []
    for p, s in files.items():
        q = f'{HERE}/{p}'
        if a.check:
            if not (os.path.isfile(q) and open(q, encoding='utf-8', newline='').read() == s):
                bad.append(p)
        else:
            with open(q, 'w', encoding='utf-8', newline='') as fh:
                fh.write(s)
        print(f'{p}: sha256 {sha(s)[:16]} ({"checked" if a.check else "written"})')
    assert not bad, f'stale generated files: {bad} (run make_k10_tools.py)'
    for slug, p in ((SLUG_K10, 'cells/k10_fleet_cell.py'), (SLUG_K10W, 'cells/k10w_fleet_cell.py')):
        assert sha(unpatch_cell(files[p], slug))[:16] == K5_CELL_SHA16
    print('MAKE_K10_TOOLS OK' + (' (--check: every generated file == make())' if a.check else ''))
    return 0


if __name__ == '__main__':
    sys.exit(main())
