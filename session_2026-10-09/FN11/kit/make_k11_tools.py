def make():
    g10 = mt10.make()
    out = {p: g10[p] for p in ('cells/k10_fleet_cell.py', 'cells/k10w_fleet_cell.py')}
    out.update({
        'cells/k11w_fleet_cell.py': mt10.cell(SLUG_K11W),
        'cells/k11w2_fleet_cell.py': mt10.cell(SLUG_K11W2),
        'build_k11.py': build_k11(),
        'build_k11fn.py': build_k11fn(),
        'fn11_check.py': fn11_check(),
        'fnw_check.py': fnw_check(),
        'box/k5_pick.py': k5_pick(),
    })
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    files = make()
    bad = []
    for p, s in files.items():
        q = f'{HERE}/{p}'
        if a.check:
            if not (os.path.isfile(q) and open(q, encoding='utf-8', newline='').read() == s):
                bad.append(p)
        else:
            with open(q, 'w', encoding='utf-8', newline='') as fh:
                fh.write(s)
        print(f'{p}: sha256 {sha(s)[:16]} ({"checked" if a.check else "written"})')
    assert not bad, f'stale generated files: {bad} (run make_k11_tools.py)'
    for slug, p in ((SLUG_K11W, 'cells/k11w_fleet_cell.py'), (SLUG_K11W2, 'cells/k11w2_fleet_cell.py')):
        assert sha(unpatch_cell(files[p], slug))[:16] == K5_CELL_SHA16
    for p in ('build_k11.py', 'build_k11fn.py', 'fn11_check.py', 'fnw_check.py', 'box/k5_pick.py'):
        compile(files[p], p, 'exec')
    for f in ('make_k10_tools.py', 'build_k2.py', 'make_k2_kernel.py', 'k2_check.py', 'fn_check.py', 'fn10_check.py',
              'make_fn_cell.py', 'wdiff.py', 'cells/k2_fleet_cell.py', 'cells/fn_ids_cell.py', 'cells/fn_n949_cell.py',
              'cells/k9n_n949_cell.py', 'n949/make_child.py', 'n949/n949_child.py', 'box/k10fnw_box_stage.py'):
        assert open(f'{HERE}/{f}', 'rb').read() == open(f'{K10}/{f}', 'rb').read(), f'{f} != the k10 copy'
    print('MAKE_K11_TOOLS OK' + (' (--check: every generated file == make(); k10 byte copies identical)' if a.check else ''))
    return 0


if __name__ == '__main__':
    sys.exit(main())
