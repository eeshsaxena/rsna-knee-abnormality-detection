#!/usr/bin/env python3
"""make_k12_tools.py (2026-10-09, Claude). Generates every K12 file that is a PROVEN K11 kit file + an exact, counted
substitution (sources read from SP/k11, read only; the reverse substitution must give back the source). `--check` =
every generated file on disk == make(). Never edit a generated file by hand.

  cells/k12_fleet_cell.py   = the K5 cell (e37f0604997cd40f) with its dataset mount tuple -> ('/tmp/k12_fleet',) (the
                              merged dir of the K12-MERGE cell) and the not-attached message -> names the merge cell
  fn12_check.py             = k11/fn11_check.py with the K12 slugs
  fnw_check.py              = k11/fnw_check.py with the K12 slugs added to SLUGS
  box/k12fnw_box_stage.py   = k11/box/k10fnw_box_stage.py (the tested FN11 / FN10-3-N70 A0 harness) + a 2nd dataset
                              symlink (env K12_DS2 = 'slug=path'), the 4-code-cell layout (fn_ids, k12_merge,
                              k2_fleet_stage, fn_n949_stage) and /tmp/k12_fleet redirected into the run dir
Hand-written (not generated): cells/k12_merge_cell.py, build_k12.py, k12_nbdiff.py, box/k12_*.py, k12_collect.sh, ...
  python make_k12_tools.py [--check]
"""
import argparse, hashlib, os, sys

HERE = os.path.dirname(os.path.abspath(__file__)).replace('\\', '/')
SP = os.path.dirname(HERE)
K11 = f'{SP}/k11'
sys.path.insert(0, HERE)
import make_k10_tools as mt10                                          # noqa: E402  (byte copy of the k10 file)

K5_CELL_SHA16 = 'e37f0604997cd40f'
K12_SLUGS = ('rsna-sub-k12fn', 'rsna-sub-k12fn-n70')
TUP_OLD = "for _c in ('/kaggle/input/datasets/eeshsaxena/rsna-knee-cnxt-fleet', '/kaggle/input/rsna-knee-cnxt-fleet'):\n"
TUP_NEW = "for _c in ('/tmp/k12_fleet',):   # K12: the merged fleet dir written by the K12-MERGE cell (k11w + k12w)\n"
MSG_OLD = "(no fleet_worker.py under /kaggle/input/.../rsna-knee-cnxt-fleet)"
MSG_NEW = "(no fleet_worker.py under /tmp/k12_fleet: the K12-MERGE cell failed, see its RESULT FAIL line)"


def sha(s):
    return hashlib.sha256(s.encode() if isinstance(s, str) else s).hexdigest()


def rd11(p):
    return open(f'{K11}/{p}', encoding='utf-8', newline='').read()


def k12_cell():
    src = open(f'{HERE}/cells/k2_fleet_cell.py', encoding='utf-8', newline='').read()
    assert sha(src)[:16] == K5_CELL_SHA16
    out = mt10.subst(src, [(TUP_OLD, TUP_NEW, 1), (MSG_OLD, MSG_NEW, 1)])
    assert 'rsna-knee-cnxt-fleet' not in out
    return out


def unpatch_k12(src):
    assert src.count(TUP_NEW) == 1 and src.count(MSG_NEW) == 1
    return src.replace(TUP_NEW, TUP_OLD).replace(MSG_NEW, MSG_OLD)


def fn12_check():
    old = ("    assert fn[0] in ('rsna-sub-k11fn', 'rsna-sub-k11fn-n70', 'rsna-sub-k11fn-d2', 'rsna-sub-k11fn-d2-n70'), "
           "f'{fn[0]} is not a K11 FN kernel'   # K11\n")
    return mt10.subst(rd11('fn11_check.py'), [
        ('"""fn11_check.py = fn10_check.py with the K11 FN slugs',
         '"""fn12_check.py = fn11_check.py with the K12 FN slugs (rsna-sub-k12fn, -n70; k12/make_k12_tools.py).\n'
         'fn11_check.py = fn10_check.py with the K11 FN slugs', 1),
        (old, f"    assert fn[0] in {K12_SLUGS!r}, f'{{fn[0]}} is not a K12 FN kernel'   # K12\n", 1)])


def fnw_check():
    old = "   # K11 (k11/make_k11_tools.py)\n"
    return mt10.subst(rd11('fnw_check.py'), [(old, f" + {K12_SLUGS!r}   # K11 (k11/make_k11_tools.py) + K12 (k12/make_k12_tools.py)\n", 1)])


def harness():
    src = rd11('box/k10fnw_box_stage.py')
    return '# K12: generated by k12/make_k12_tools.py from k11/box/k10fnw_box_stage.py (exact counted substitutions; never edit by hand)\n' + \
        mt10.subst(src, [
            ("K10_DS_SLUG = os.environ.get('K10_DS_SLUG', 'rsna-knee-cnxt-fleet-k10')   # K10-DS: the fleet dataset mount name (negative test: the K9 slug)\n",
             "K10_DS_SLUG = os.environ.get('K10_DS_SLUG', 'rsna-knee-cnxt-fleet-k10')   # K10-DS: the fleet dataset mount name (negative test: the K9 slug)\n"
             "K12_DS2 = os.environ.get('K12_DS2', '')   # K12: 'slug=path' of the 2nd dataset (k12w, the D-OAI weights); empty = not attached\n", 1),
            ("        os.symlink(os.path.abspath(os.path.expanduser(a.fleet_ds)), f'{inp}/datasets/eeshsaxena/{K10_DS_SLUG}')\n",
             "        os.symlink(os.path.abspath(os.path.expanduser(a.fleet_ds)), f'{inp}/datasets/eeshsaxena/{K10_DS_SLUG}')\n"
             "        if K12_DS2:                                                      # K12: the 2nd dataset\n"
             "            _s2, _p2 = K12_DS2.split('=', 1)\n"
             "            os.symlink(os.path.abspath(os.path.expanduser(_p2)), f'{inp}/datasets/eeshsaxena/{_s2}')\n", 1),
            ("    want = ['fn_ids', 'k2_fleet_stage', 'fn_n949_stage'] if a.kernel == 'fn' else ['fn_ids', 'fn_n949_stage']",
             "    want = ['fn_ids', 'k12_merge', 'k2_fleet_stage', 'fn_n949_stage'] if a.kernel == 'fn' else ['fn_ids', 'fn_n949_stage']", 1),
            ("    k2cfg = eval(cells[1][1].split", "    k2cfg = eval(cells[2][1].split", 1),
            ("        cells = [cells[0], ('STUB_FLEET', None), cells[2]]", "        cells = [cells[0], cells[1], ('STUB_FLEET', None), cells[3]]", 1),
            ("        src = src.replace('/kaggle/input', inp).replace('/kaggle/working', work)\n        bad =",
             "        src = src.replace('/kaggle/input', inp).replace('/kaggle/working', work).replace('/tmp/k12_fleet', f'{out}/k12_fleet')   # K12\n        bad =", 1),
        ])


def make():
    return {'cells/k12_fleet_cell.py': k12_cell(), 'fn12_check.py': fn12_check(), 'fnw_check.py': fnw_check(),
            'box/k12fnw_box_stage.py': harness()}


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--check', action='store_true')
    a = ap.parse_args()
    files = make()
    bad = []
    for p, s in files.items():
        q = f'{HERE}/{p}'
        if a.check:
            if not (os.path.isfile(q) and open(q, encoding='utf-8', newline='').read() == s):
                bad.append(p)
        else:
            with open(q, 'w', encoding='utf-8', newline='') as fh:
                fh.write(s)
        print(f'{p}: sha256 {sha(s)[:16]} ({"checked" if a.check else "written"})')
    assert not bad, f'stale generated files: {bad} (run make_k12_tools.py)'
    k5 = open(f'{HERE}/cells/k2_fleet_cell.py', encoding='utf-8', newline='').read()
    assert unpatch_k12(files['cells/k12_fleet_cell.py']) == k5 and sha(k5)[:16] == K5_CELL_SHA16
    for p in ('fn12_check.py', 'fnw_check.py', 'box/k12fnw_box_stage.py', 'cells/k12_fleet_cell.py', 'cells/k12_merge_cell.py'):
        compile(files[p] if p in files else open(f'{HERE}/{p}', encoding='utf-8').read(), p, 'exec')
    for f in ('make_k10_tools.py', 'k2_check.py', 'fn_check.py', 'k9n_check.py', 'wdiff.py', 'make_fn_cell.py', 'fn11_check.py',
              'cells/k2_fleet_cell.py', 'cells/k11w_fleet_cell.py', 'cells/fn_ids_cell.py', 'cells/fn_n949_cell.py',
              'cells/k9n_n949_cell.py', 'n949/make_child.py', 'n949/n949_child.py', 'box/k5_pick.py', 'box/k10fnw_box_stage.py'):
        assert open(f'{HERE}/{f}', 'rb').read() == open(f'{K11}/{f}', 'rb').read(), f'{f} != the k11 copy'
    print('MAKE_K12_TOOLS OK' + (' (--check: every generated file == make(); k11 byte copies identical)' if a.check else ''))
    return 0


if __name__ == '__main__':
    sys.exit(main())
